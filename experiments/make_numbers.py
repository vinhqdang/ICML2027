"""Write paper/numbers.tex: LaTeX macros for every number quoted in the text of the GPU experiments, computed from
results/main_gpu/summary.json (itself computed from the raw logs by experiments/aggregate_gpu.py).
\\val{target}{method}{metric}{m|s} gives the mean or the sample std (ddof=1); \\ms{target}{method}{metric} gives
mean $\\pm$ std; \\cnt{target}{method} gives the number of seeds. Derived ratios: \\ratio{name}.
Usage: python experiments/aggregate_gpu.py && python experiments/make_numbers.py"""
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = json.load(open(os.path.join(ROOT, 'results', 'main_gpu', 'summary.json')))


def fmt(x, sig):
    if not np.isfinite(x):
        return '--'
    if x != 0 and (abs(x) >= 1e4 or abs(x) < 1e-3):
        m, e = f'{x:.{sig - 1}e}'.split('e')
        return f'{m}\\!\\cdot\\!10^{{{int(e)}}}'
    return f'{x:.{sig}g}'


lines = ['% generated by experiments/make_numbers.py -- do not edit',
         r'\newcommand{\val}[4]{\csname v:#1:#2:#3:#4\endcsname}',
         r'\newcommand{\ms}[3]{$\csname v:#1:#2:#3:m\endcsname\pm\csname v:#1:#2:#3:s\endcsname$}',
         r'\newcommand{\cnt}[2]{\csname n:#1:#2\endcsname}',
         r'\newcommand{\ratio}[1]{\csname r:#1\endcsname}']


def d(name, v):
    lines.append(f'\\expandafter\\def\\csname {name}\\endcsname{{{v}}}')


for t, ms in S.items():
    if not isinstance(ms, dict):
        d('r:true_major_well', fmt(ms, 3))
        continue
    for m, e in ms.items():
        d(f'n:{t}:{m}', e['n'])
        for k, v in e.items():
            if isinstance(v, dict):
                d(f'v:{t}:{m}:{k}:m', fmt(v['mean'], 3))
                d(f'v:{t}:{m}:{k}:s', fmt(v['std'], 2))


def mean(t, m, k):
    return S[t][m][k]['mean']


def ratio(name, a, b, sig=2):
    d(f'r:{name}', fmt(a / b, sig))


ratio('mw_ew1_idem_over_ea', mean('mw32', 'idem', 'energy_w1'), mean('mw32', 'aem_ea', 'energy_w1'))
ratio('mw_ew1_idem_over_ref', mean('mw32', 'idem', 'energy_w1'), mean('mw32', 'aem_ea_refine', 'energy_w1'))
if 'aem_cold' in S['mw32']:
    ratio('mw_ew1_idem_over_cold', mean('mw32', 'idem', 'energy_w1'), mean('mw32', 'aem_cold', 'energy_w1'))
ratio('mw_var_idem_over_ea', mean('mw32', 'idem', 'within_var'), 1.0)
d('r:mw_ew1_ratio_lo', fmt(min(mean('mw32', 'idem', 'energy_w1') / mean('mw32', m, 'energy_w1') for m in S['mw32'] if m != 'idem'), 2))
d('r:mw_ew1_ratio_hi', fmt(max(mean('mw32', 'idem', 'energy_w1') / mean('mw32', m, 'energy_w1') for m in S['mw32'] if m != 'idem'), 2))
for t in ('gmm16', 'mw32', 'dw4', 'lj13'):
    for m in S[t]:
        d(f'r:evals_over_idem:{t}:{m}', fmt(mean(t, m, 'n_energy_evals') / mean(t, 'idem', 'n_energy_evals'), 3))
        d(f'r:gpu_hours:{t}:{m}', fmt(mean(t, m, 'wall_time') * S[t][m]['n'] / 3600, 2))
tot = sum(S[t][m]['wall_time']['mean'] * S[t][m]['n'] for t in ('gmm16', 'mw32', 'dw4', 'lj13') for m in S[t])
d('r:gpu_hours_total', fmt(tot / 3600, 2))
# reference-chain statistics
for t in ('dw4', 'lj13'):
    j = json.load(open(os.path.join(ROOT, 'results', 'ref', f'{t}_stability.json')))
    d(f'ref:{t}:w1halves', fmt(j['energy_w1_halves'], 2))
    d(f'ref:{t}:w1chains', fmt(j['energy_w1_chain_halves'], 2))
    d(f'ref:{t}:acc', fmt(j['acceptance'], 3))
open(os.path.join(ROOT, 'paper', 'numbers.tex'), 'w').write('\n'.join(lines) + '\n')
print(len(lines), 'macros')
